"""Write data/engravings.json from the 2013 engraving research dataset.

Usage: python3 -I tools/assets/build_engravings.py [path/to/engravings-2013.json]

The default input is ../analysis/engravings-2013/engravings-2013.json next to this
checkout. That dataset decodes the 2013-07-06 official CountermarkXMLInfo and dates
the later 2013 additions; design/notes/engravings-2013.md records the provenance.
Installed: every 2013 ability and skill engraving whose bound species (and, for skill
engravings, move) exists in the catalog, plus 10157 on the 2013/2014 boundary.
Universal engravings (2014, IDs 40001+) are excluded.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SOURCE = ROOT.parent / 'analysis' / 'engravings-2013' / 'engravings-2013.json'
OUT = ROOT / 'data' / 'engravings.json'
INSTALLED = {'usable', 'boundary:usable'}


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
    research = json.loads(source.read_text())
    rows = []
    for e in research['engravings']:
        if e['status'] not in INSTALLED:
            continue
        if e['slot'] not in ('ability', 'skill'):
            raise SystemExit(f"unexpected slot {e['slot']} for {e['id']}")
        row = {
            'id': str(e['id']),
            'name': {'zh': e['name']},
            'slot': e['slot'],
            'stats': e.get('stats', {}),
            'species': e['species'],
            'levelMin': e['level_min'],
            'maxOwned': e['max_owned'],
            'effect': {'code': e['effect_code'], 'arg': e['arg'], 'desc': e['effect_desc']},
            'era': e['era'],
            'source': e['value_source'].split()[0],
        }
        if e['slot'] == 'skill':
            row['moveIds'] = e['move_ids']
        if e.get('source_move_id'):
            row['sourceMoveId'] = e['source_move_id']
        if e['notes']:
            row['notes'] = e['notes']
        if e['status'].startswith('boundary'):
            row['boundary'] = True
        rows.append(row)
    doc = {
        '_note': 'Generated by tools/assets/build_engravings.py; provenance in design/notes/engravings-2013.md.',
        'engravings': rows,
    }
    OUT.write_text(json.dumps(doc, ensure_ascii=False, separators=(',', ':')) + '\n')
    print(f'wrote {OUT.relative_to(ROOT)}: {len(rows)} engravings')


if __name__ == '__main__':
    main()
